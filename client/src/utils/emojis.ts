// Provide search tags for emojis
const emojiTags: Record<string, string[]> = {
  '❤️': ['heart', 'love'],
  '😂': ['laugh', 'cry', 'tears', 'joy'],
  '👍': ['thumbs', 'up', 'like', 'approve'],
  '🔥': ['fire', 'hot', 'lit'],
  '😢': ['cry', 'sad', 'tear'],
  '😮': ['wow', 'surprise', 'open', 'mouth'],
  // Simplified search mapping
  '🐶': ['dog', 'puppy'],
  '🐱': ['cat', 'kitty'],
  '🍔': ['burger', 'food'],
  '⚽': ['soccer', 'football', 'ball'],
  '🚗': ['car', 'auto'],
  '💡': ['light', 'bulb', 'idea']
};

export function searchEmojis(query: string): string[] {
  if (!query) return [];
  const q = query.toLowerCase();
  
  const results = new Set<string>();
  
  // Basic tag search
  for (const [emoji, tags] of Object.entries(emojiTags)) {
    if (tags.some(tag => tag.includes(q))) {
      results.add(emoji);
    }
  }
  
  // If we want a more robust search, we could iterate over all emojis 
  // but without a full metadata dictionary, it's limited.
  
  return Array.from(results);
}
